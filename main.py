    if msg in GAME_DATA:
        q_item = random.choice(GAME_DATA[msg])
        current_games[chat_id] = {"q": q_item["q"], "a": q_item["a"], "cat": msg}
        text = f"<b>𓆩 💎 مسابقة بنك معين الدولي 💎 𓆪</b>\n\n"
